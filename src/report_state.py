"""
report_state.py — Session-state manager for report sections and content blocks.

A "report" in session state is:
  st.session_state["report"] = {
    "meta": { title, subject, experiment_no, ... },
    "sections": [
      {
        "id": str,
        "name": str,
        "blocks": [
          { "id": str, "type": "text"|"code"|"table"|"image", ...type-specific keys }
        ]
      }
    ]
  }

All mutations go through functions here so app.py stays clean.
"""
import uuid
import copy
from typing import List, Dict, Any, Optional
import streamlit as st

# ── Default section list ──────────────────────────────────────────────────────

DEFAULT_SECTIONS = [
    "Aim",
    "Objectives",
    "Theory",
    "Requirements",
    "Algorithm",
    "Procedure",
    "Source Code",
    "Output / Screenshots",
    "Observations",
    "Result",
    "Conclusion",
]

# ── Report initialization ─────────────────────────────────────────────────────

def _new_section(name: str) -> Dict[str, Any]:
    return {"id": str(uuid.uuid4()), "name": name, "blocks": []}


def _new_block(block_type: str, **kwargs) -> Dict[str, Any]:
    base = {"id": str(uuid.uuid4()), "type": block_type}
    if block_type == "text":
        base["content"] = kwargs.get("content", "")
    elif block_type == "code":
        base["content"] = kwargs.get("content", "")
        base["language"] = kwargs.get("language", "text")
    elif block_type == "table":
        base["headers"] = kwargs.get("headers", ["Column 1", "Column 2"])
        base["rows"] = kwargs.get("rows", [["", ""]])
        base["caption"] = kwargs.get("caption", "")
    elif block_type == "image":
        base["bytes"] = kwargs.get("bytes", None)
        base["filename"] = kwargs.get("filename", "")
        base["caption"] = kwargs.get("caption", "")
    return base


def init_report():
    """Initialize a blank report in session state if not already present."""
    if "report" not in st.session_state:
        sections = [_new_section(name) for name in DEFAULT_SECTIONS]
        st.session_state["report"] = {
            "meta": {
                "title": "",
                "subject": "",
                "experiment_no": "",
                "experiment_title": "",
                "student_name": "",
                "roll_number": "",
                "class_section": "",
                "faculty_name": "",
                "submission_date": "",
                "institution": "",
                "subject_code": "",
            },
            "sections": sections,
        }
    if "active_section_id" not in st.session_state:
        sections = st.session_state["report"]["sections"]
        st.session_state["active_section_id"] = sections[0]["id"] if sections else None
    if "saved_report_id" not in st.session_state:
        st.session_state["saved_report_id"] = None


def reset_report():
    """Wipe the current report and start fresh."""
    for key in ["report", "active_section_id", "saved_report_id"]:
        st.session_state.pop(key, None)
    init_report()


