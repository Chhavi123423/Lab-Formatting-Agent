# ── Meta helpers ──────────────────────────────────────────────────────────────

def get_meta() -> Dict[str, Any]:
    return st.session_state["report"]["meta"]


def update_meta(**kwargs):
    st.session_state["report"]["meta"].update(kwargs)


# ── Section helpers ───────────────────────────────────────────────────────────

def get_sections() -> List[Dict[str, Any]]:
    return st.session_state["report"]["sections"]


def get_section_by_id(section_id: str) -> Optional[Dict[str, Any]]:
    for s in get_sections():
        if s["id"] == section_id:
            return s
    return None


def add_section(name: str = "New Section", position: Optional[int] = None):
    """Add a new section. Appends to end if no position specified."""
    sections = get_sections()
    new_sec = _new_section(name)
    if position is not None:
        sections.insert(position, new_sec)
    else:
        sections.append(new_sec)
    st.session_state["active_section_id"] = new_sec["id"]


def rename_section(section_id: str, new_name: str):
    sec = get_section_by_id(section_id)
    if sec:
        sec["name"] = new_name.strip() or sec["name"]


def duplicate_section(section_id: str):
    sections = get_sections()
    for i, sec in enumerate(sections):
        if sec["id"] == section_id:
            clone = copy.deepcopy(sec)
            clone["id"] = str(uuid.uuid4())
            clone["name"] = sec["name"] + " (copy)"
            # Deep-clone block ids
            for blk in clone["blocks"]:
                blk["id"] = str(uuid.uuid4())
            sections.insert(i + 1, clone)
            st.session_state["active_section_id"] = clone["id"]
            break


def delete_section(section_id: str):
    sections = get_sections()
    idx = next((i for i, s in enumerate(sections) if s["id"] == section_id), None)
    if idx is not None:
        sections.pop(idx)
        # Update active selection
        if sections:
            new_idx = min(idx, len(sections) - 1)
            st.session_state["active_section_id"] = sections[new_idx]["id"]
        else:
            st.session_state["active_section_id"] = None


def move_section_up(section_id: str):
    sections = get_sections()
    idx = next((i for i, s in enumerate(sections) if s["id"] == section_id), None)
    if idx is not None and idx > 0:
        sections[idx], sections[idx - 1] = sections[idx - 1], sections[idx]


def move_section_down(section_id: str):
    sections = get_sections()
    idx = next((i for i, s in enumerate(sections) if s["id"] == section_id), None)
    if idx is not None and idx < len(sections) - 1:
        sections[idx], sections[idx + 1] = sections[idx + 1], sections[idx]


def section_has_content(section_id: str) -> bool:
    sec = get_section_by_id(section_id)
    if not sec:
        return False
    for blk in sec["blocks"]:
        if blk["type"] == "text" and blk.get("content", "").strip():
            return True
        if blk["type"] == "code" and blk.get("content", "").strip():
            return True
        if blk["type"] == "table" and any(
            any(cell.strip() for cell in row) for row in blk.get("rows", [])
        ):
            return True
        if blk["type"] == "image" and blk.get("bytes"):
            return True
    return False


# ── Block helpers ─────────────────────────────────────────────────────────────

def add_block(section_id: str, block_type: str, **kwargs):
    sec = get_section_by_id(section_id)
    if sec is not None:
        sec["blocks"].append(_new_block(block_type, **kwargs))


def update_block(section_id: str, block_id: str, **kwargs):
    sec = get_section_by_id(section_id)
    if sec:
        for blk in sec["blocks"]:
            if blk["id"] == block_id:
                blk.update(kwargs)
                break


def delete_block(section_id: str, block_id: str):
    sec = get_section_by_id(section_id)
    if sec:
        sec["blocks"] = [b for b in sec["blocks"] if b["id"] != block_id]


def move_block_up(section_id: str, block_id: str):
    sec = get_section_by_id(section_id)
    if not sec:
        return
    blocks = sec["blocks"]
    idx = next((i for i, b in enumerate(blocks) if b["id"] == block_id), None)
    if idx is not None and idx > 0:
        blocks[idx], blocks[idx - 1] = blocks[idx - 1], blocks[idx]


def move_block_down(section_id: str, block_id: str):
    sec = get_section_by_id(section_id)
    if not sec:
        return
    blocks = sec["blocks"]
    idx = next((i for i, b in enumerate(blocks) if b["id"] == block_id), None)
    if idx is not None and idx < len(blocks) - 1:
        blocks[idx], blocks[idx + 1] = blocks[idx + 1], blocks[idx]


# ── Serialization (for save/load) ─────────────────────────────────────────────

def report_to_dict() -> Dict[str, Any]:
    """Serialize the full report to a JSON-safe dict (image bytes excluded)."""
    report = st.session_state["report"]
    result = {"meta": dict(report["meta"]), "sections": []}
    for sec in report["sections"]:
        sec_copy = {"id": sec["id"], "name": sec["name"], "blocks": []}
        for blk in sec["blocks"]:
            blk_copy = {k: v for k, v in blk.items() if k != "bytes"}
            blk_copy["has_image"] = bool(blk.get("bytes"))
            sec_copy["blocks"].append(blk_copy)
        result["sections"].append(sec_copy)
    return result


def report_from_dict(data: Dict[str, Any]):
    """Load a report from a saved dict (images not restored — by design)."""
    st.session_state["report"] = {
        "meta": data.get("meta", {}),
        "sections": data.get("sections", []),
    }
    sections = st.session_state["report"]["sections"]
    if sections:
        st.session_state["active_section_id"] = sections[0]["id"]


# ── Raw-text import (backward-compat with old paste workflow) ─────────────────

def import_from_raw_text(raw_text: str, image_bytes: Optional[bytes] = None):
    """
    Parse raw pasted text using the existing heading-detector pipeline
    and populate report sections from it. Preserves all existing content
    principles (formatting only).
    """
    from src.preprocessor import clean_input_text
    from src.heading_detector import extract_sections_with_llm_fallback

    cleaned = clean_input_text(raw_text)
    raw_sections = extract_sections_with_llm_fallback(cleaned)

    sections = []
    for sec in raw_sections:
        new_sec = _new_section(sec["heading"])
        content = sec.get("content", "").strip()
        if content:
            # Detect if content is code
            from src.content_detector import is_code_block, detect_programming_language
            is_code, lang = is_code_block(content)
            if is_code or sec["heading"].upper() in ["CODE", "SOURCE CODE", "PROGRAM", "IMPLEMENTATION"]:
                lang = detect_programming_language(content) if not is_code else lang
                new_sec["blocks"].append(_new_block("code", content=content, language=lang))
            else:
                new_sec["blocks"].append(_new_block("text", content=content))

        # Attach image to OUTPUT section
        if image_bytes and sec["heading"].upper() in ["OUTPUT", "SCREENSHOT", "EXECUTION OUTPUT"]:
            new_sec["blocks"].append(_new_block("image", bytes=image_bytes, filename="screenshot.png", caption="Figure: Program Output"))

        sections.append(new_sec)

    st.session_state["report"]["sections"] = sections
    if sections:
        st.session_state["active_section_id"] = sections[0]["id"]

